namespace Blazorade.Bootstrap.Components
{
    /// <summary>
    /// Specifies where a card image is rendered.
    /// </summary>
    public enum CardImagePosition
    {
        /// <summary>
        /// Renders the image before the card content.
        /// </summary>
        Top,

        /// <summary>
        /// Renders the image after the card content.
        /// </summary>
        Bottom,

        /// <summary>
        /// Renders the image as the card background.
        /// </summary>
        Overlay
    }
}